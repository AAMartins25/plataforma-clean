CREATE TABLE IF NOT EXISTS controle_financeiro (
    id integer PRIMARY KEY CHECK (id=1),
    modo varchar(16) NOT NULL CHECK (modo IN ('NORMAL','PAUSADO','RECUPERACAO')),
    geracao integer NOT NULL DEFAULT 0,
    alterado_em timestamptz NOT NULL DEFAULT now(),
    alterado_por integer NULL,
    motivo varchar(300) NOT NULL DEFAULT ''
);
COMMENT ON TABLE controle_financeiro IS 'resumao:migration016:v1';

CREATE TABLE IF NOT EXISTS notificacoes_mp (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave varchar(160) NOT NULL UNIQUE,
    payment_id varchar(64) NOT NULL,
    fonte varchar(16) NOT NULL CHECK (fonte IN ('WEBHOOK','RECONCILIACAO')),
    recebida_em timestamptz NOT NULL DEFAULT now(),
    estado varchar(16) NOT NULL DEFAULT 'PENDENTE'
        CHECK (estado IN ('PENDENTE','ERRO','CONCLUIDO')),
    tentativas integer NOT NULL DEFAULT 0 CHECK (tentativas>=0),
    erro varchar(200) NULL,
    concluida_em timestamptz NULL,
    resultado jsonb NULL
);
COMMENT ON TABLE notificacoes_mp IS 'resumao:migration016:v1';
CREATE INDEX IF NOT EXISTS ix_notificacoes_mp_pendentes
    ON notificacoes_mp(estado,id) WHERE estado <> 'CONCLUIDO';

